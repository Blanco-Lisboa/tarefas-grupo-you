import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
const require = createRequire(join(process.env.APPDATA, "npm", "node_modules", "/"));
const { chromium } = require("playwright");
const PASTA = fileURLToPath(new URL("./", import.meta.url));
const REF = join(PASTA, "../../docs/referencias/2026-10-19-rodada-4/");
const nav = await chromium.launch({ channel: "chrome", args: ["--window-position=-3000,0"] });
const p = await nav.newPage({ viewport: { width: 1440, height: 760 } });
const marca = () => p.evaluate(() => { const d = document.getElementById("iw") ?? document.body.appendChild(Object.assign(document.createElement("div"), { id: "iw" })); d.textContent = "innerWidth " + innerWidth; d.style.cssText = "position:fixed;left:8px;bottom:8px;z-index:2147483647;background:#fff;font:700 12px monospace;padding:4px 8px"; });
await p.goto("http://localhost:3100/conteudos", { waitUntil: "networkidle" });
await p.waitForTimeout(1000);
const titulo = "Ideias de Reels de outubro";
const col = (n) => p.locator(`[data-etapa="${n}"]`);
const antes = await col("ideia").locator(".conteudos-titulo", { hasText: titulo }).count();
const card = p.locator(".conteudos-cartao", { hasText: titulo });
const b = await card.boundingBox();
const alvo = await col("roteiro").boundingBox();
await p.mouse.move(b.x + 60, b.y + 30);
await p.mouse.down();
const x1 = alvo.x + alvo.width / 2, y1 = alvo.y + 200;
for (let i = 1; i <= 12; i++) await p.mouse.move(b.x + 60 + (x1 - b.x - 60) * i / 12, b.y + 30 + (y1 - b.y - 30) * i / 12);
await p.waitForTimeout(300);
await marca();
console.log("tilt", await card.evaluate((e) => getComputedStyle(e).transform), "destino", await col("roteiro").getAttribute("data-destino"));
await p.screenshot({ path: join(REF, "47-conteudos-meio-do-arraste.png") });
await p.mouse.up();
await p.waitForTimeout(400);
await marca();
console.log("depois: no roteiro", await col("roteiro").locator(".conteudos-titulo", { hasText: titulo }).count(), "na ideia antes/agora", antes, await col("ideia").locator(".conteudos-titulo", { hasText: titulo }).count());
await p.screenshot({ path: join(REF, "47-conteudos-depois-de-soltar.png") });
await p.reload({ waitUntil: "networkidle" });
await p.waitForTimeout(800);
await marca();
console.log("apos recarregar: no roteiro", await col("roteiro").locator(".conteudos-titulo", { hasText: titulo }).count());
await p.screenshot({ path: join(REF, "47-conteudos-depois-de-recarregar.png") });
// clique simples ainda abre a ficha
await p.locator(".conteudos-titulo").first().click();
console.log("ficha abre", await p.locator("dialog, [role=dialog]").count());
await nav.close();
