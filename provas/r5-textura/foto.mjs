import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
const require = createRequire(join(process.env.APPDATA, "npm", "node_modules", "/"));
const { chromium } = require("playwright");
const PASTA = fileURLToPath(new URL("./", import.meta.url));
const nav = await chromium.launch({ args: ["--window-position=-3000,0"] });
const p = await nav.newPage({ viewport: { width: 1903, height: 910 } });
await p.goto("http://127.0.0.1:3100/pastas", { waitUntil: "networkidle" });
const t0 = Date.now();
const tiraFoto = async (nome) => p.screenshot({ path: join(PASTA, nome) });
await p.waitForTimeout(300);
await tiraFoto("pastas-1903-cedo.png");
await p.waitForFunction(() => [...document.images].every((i) => i.complete || i.loading === "lazy"), null, { timeout: 30000 });
await p.waitForFunction(() => { const c = [...document.querySelectorAll("canvas")]; return c.length > 0 && c.every((x) => x.dataset.ready); }, null, { timeout: 60000 });
const info = await p.evaluate(() => ({ imgs: document.images.length, imgsOk: [...document.images].every((i) => i.complete), canvas: document.querySelectorAll("canvas").length, prontos: document.querySelectorAll("canvas[data-ready]").length }));
console.log(JSON.stringify(info), "ms até pronto:", Date.now() - t0);
await p.evaluate(() => { const d = document.createElement("div"); d.textContent = "innerWidth " + innerWidth; d.style.cssText = "position:fixed;left:8px;bottom:8px;z-index:2147483647;background:#fff;font:700 12px monospace;padding:4px 8px"; document.body.append(d); });
await tiraFoto("pastas-1903.png");
await nav.close();
