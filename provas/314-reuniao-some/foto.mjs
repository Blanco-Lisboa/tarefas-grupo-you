import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
const require = createRequire(join(process.env.APPDATA, "npm", "node_modules", "/"));
const { chromium } = require("playwright");
const PASTA = fileURLToPath(new URL("./", import.meta.url));
const b64 = (o) => Buffer.from(JSON.stringify(o)).toString("base64url");
const exp = 1893456000, uid = "u-natham";
const jwt = [b64({ alg: "HS256", typ: "JWT" }), b64({ sub: uid, exp, role: "authenticated", aud: "authenticated" }), b64("assinatura")].join(".");
const sessao = { access_token: jwt, refresh_token: "x", expires_in: 3600, expires_at: exp, token_type: "bearer", user: { id: uid, aud: "authenticated", role: "authenticated", email: "foto@exemplo.invalid", app_metadata: {}, user_metadata: {}, created_at: "2026-10-19T00:00:00Z" } };
const marca = () => { const d = document.createElement("div"); d.textContent = "innerWidth " + innerWidth; d.style.cssText = "position:fixed;left:4px;bottom:4px;z-index:2147483647;background:#000;color:#fff;font:700 10px monospace;padding:2px 6px"; document.body.append(d); };
const nav = await chromium.launch({ args: ["--window-position=-32000,0"] });
const ctx = await nav.newContext({ viewport: { width: 1440, height: 760 } });
await ctx.addCookies([{ name: "sb-127-auth-token", value: "base64-" + b64(sessao), domain: "127.0.0.1", path: "/" }]);
const p = await ctx.newPage();
const erros = [];
p.on("pageerror", (e) => erros.push(e.message));
p.on("console", (m) => m.type() === "error" && erros.push(m.text()));
await p.goto("http://127.0.0.1:3101/conteudos", { waitUntil: "networkidle" });
await p.waitForTimeout(1000);
const coluna = () => p.locator('[data-etapa="analise"]');
const antes = await coluna().locator("text=Reunião com Junio").count();
await coluna().getByRole("button", { name: /\+|novo|adicionar/i }).first().click();
await p.waitForSelector("dialog[open]");
await p.getByLabel("Título").fill("Reunião com Junio");
const empresa = p.locator("dialog select").first();
console.log("selects:", await p.locator("dialog select").count());
await p.locator('dialog input[type="file"]').first().setInputFiles(join(PASTA, "clip.mp4"));
await p.waitForTimeout(500);
await p.getByRole("button", { name: "Salvar", exact: true }).click();
await p.waitForTimeout(2500);
const depoisSalvar = await coluna().locator("text=Reunião com Junio").count();
await p.evaluate(marca);
await p.screenshot({ path: join(PASTA, "1-depois-de-salvar.png") });
await p.reload({ waitUntil: "networkidle" });
await p.waitForTimeout(1500);
const depoisRecarregar = await coluna().locator("text=Reunião com Junio").count();
await p.evaluate(marca);
await p.screenshot({ path: join(PASTA, "2-depois-de-recarregar.png") });
console.log({ antes, depoisSalvar, depoisRecarregar, erros });
await nav.close();
