import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
const require = createRequire(join(process.env.APPDATA, "npm", "node_modules", "/"));
const { chromium } = require("playwright");
const PASTA = fileURLToPath(new URL("./", import.meta.url));
const b64 = (o) => Buffer.from(JSON.stringify(o)).toString("base64url");
const exp = 1893456000, uid = "u-natham";
const jwt = [b64({ alg: "HS256", typ: "JWT" }), b64({ sub: uid, exp, role: "authenticated", aud: "authenticated" }), b64("a")].join(".");
const sessao = { access_token: jwt, refresh_token: "x", expires_in: 3600, expires_at: exp, token_type: "bearer", user: { id: uid, aud: "authenticated", role: "authenticated", email: "f@e.invalid", app_metadata: {}, user_metadata: {}, created_at: "2026-10-19T00:00:00Z" } };
const nav = await chromium.launch({ args: ["--window-position=-3000,0"] });
const ctx = await nav.newContext({ viewport: { width: 1903, height: 900 } });
await ctx.addCookies([{ name: "sb-127-auth-token", value: "base64-" + b64(sessao), domain: "127.0.0.1", path: "/" }]);
const p = await ctx.newPage();
const marca = () => p.evaluate(() => { const d = document.createElement("div"); d.textContent = "innerWidth " + innerWidth; d.style.cssText = "position:fixed;left:4px;bottom:4px;z-index:2147483647;background:#000;color:#fff;font:700 10px monospace;padding:2px 6px"; document.body.append(d); });
await p.goto("http://127.0.0.1:3101/pastas", { waitUntil: "networkidle" });
await p.waitForTimeout(3000);
const pasta = p.getByRole("button", { name: /^Abrir Ideias de conteúdo/ }).first();
await pasta.hover();
await p.waitForTimeout(1000);
console.log("Ideias aberta no hover:", await p.locator(".gf-root[data-open]").count());
await marca();
await p.screenshot({ path: join(PASTA, "hover-ideias.png") });
await p.mouse.move(1000, 600);
await p.waitForTimeout(800);
console.log("fecha ao tirar o mouse:", await p.locator(".gf-root[data-open]").count() === 0);
await p.getByRole("button", { name: /^Abrir Reels/ }).first().hover();
await p.waitForTimeout(800);
console.log("Reels aberta só no hover:", await p.locator(".gf-root[data-open]").count());
await p.mouse.move(1000, 600);
await pasta.click();
console.log("clique abre o mural:", await p.locator("dialog.mural[open]").count());
await nav.close();
