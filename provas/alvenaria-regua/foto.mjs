import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
const require = createRequire(join(process.env.APPDATA, "npm", "node_modules", "/"));
const { chromium } = require("playwright");
const PASTA = fileURLToPath(new URL("./", import.meta.url));
const nav = await chromium.launch({ args: ["--window-position=-3000,0"] });
const p = await nav.newPage({ viewport: { width: 1440, height: 760 } });
const marca = () => p.evaluate(() => { document.getElementById("m")?.remove(); const d = document.createElement("div"); d.id = "m"; d.textContent = "innerWidth " + innerWidth; d.style.cssText = "position:fixed;right:8px;top:8px;z-index:99999;background:#fff;font:700 12px monospace;padding:4px 8px"; document.body.append(d); });
const foto = async (n) => { await marca(); await p.screenshot({ path: PASTA + n }); };
p.on("response", (r) => { if (r.status() >= 400) console.log("HTTP", r.status(), r.request().method(), r.url().slice(0, 110)); });
await p.goto("http://127.0.0.1:3221/entrar", { waitUntil: "networkidle" });
await p.goto("http://127.0.0.1:3121/conteudos", { waitUntil: "networkidle" });
await p.waitForTimeout(3000);
await p.getByText("Reels: dica rápida de IR").first().click();
await p.locator("dialog.ficha[open]").waitFor();
const antes = await p.locator("dialog.ficha .ficha-anexos-trava .ficha-anexo").count();
await p.locator("dialog.ficha input[type=file]").last().setInputFiles({ name: "ir-legendado-final.mp4", mimeType: "video/mp4", buffer: Buffer.alloc(2 * 1024 * 1024) });
await p.waitForTimeout(6000);
console.log("miniaturas antes/depois:", antes, await p.locator("dialog.ficha .ficha-anexos-trava .ficha-anexo").count());
console.log("anexos ativos:", await p.locator("dialog.ficha .ficha-anexos-trava .ficha-anexo-mini").evaluateAll((l) => l.map((e) => e.title)));
console.log("recado original:", await p.locator("dialog.ficha .ficha-dica", { hasText: "Sem legenda" }).allInnerTexts());
await p.locator("dialog.ficha .ficha-anexos-trava").scrollIntoViewIfNeeded();
await foto("1-legendado-subiu-1440.png");
await p.locator("dialog.ficha button[type=submit]").click();
await p.waitForTimeout(2500);
console.log("erro depois de salvar:", await p.locator(".ficha-erro").allInnerTexts(), "| ficha aberta:", await p.locator("dialog.ficha[open]").count());
await foto("2-salvou-sem-erro-1440.png");
await nav.close();
