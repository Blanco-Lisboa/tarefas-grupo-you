// Caminho feliz do convite com sessão REAL de um usuário de teste (descartável): link com #access_token -> /entrar/nova-senha -> escolhe senha -> app.
import { createRequire } from "node:module";
import { join } from "node:path";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const require = createRequire(join(process.env.APPDATA, "npm", "node_modules", "/"));
const { chromium } = require("playwright");
const PASTA = fileURLToPath(new URL("./", import.meta.url));
const env = Object.fromEntries(readFileSync(join(PASTA, "../../.env.local"), "utf8").split(/\r?\n/).filter(Boolean).map((l) => l.split(/=(.*)/s).slice(0, 2)));
const r = await fetch(`${env.NEXT_PUBLIC_SUPABASE_URL}/auth/v1/token?grant_type=password`, { method: "POST", headers: { apikey: env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY, "content-type": "application/json" }, body: JSON.stringify({ email: "teste-convite@exemplo.invalid", password: process.env.SENHA ?? "Tmp-Convite-12345" }) });
const s = await r.json();
if (!s.access_token) throw new Error("sem sessão de teste: " + JSON.stringify(s));
const nav = await chromium.launch({ headless: true });
const p = await nav.newPage({ viewport: { width: 1280, height: 800 } });
const erros = [];
p.on("pageerror", (e) => erros.push(String(e)));
const link = `http://127.0.0.1:3100/#access_token=${s.access_token}&refresh_token=${s.refresh_token}&expires_in=3600&token_type=bearer&type=${process.argv[2] ?? "invite"}`;
await p.goto(link, { waitUntil: "networkidle" });
await p.waitForURL("**/entrar/nova-senha", { timeout: 15000 });
await p.waitForSelector("input[name=senha]");
console.log("1) chegou em:", new URL(p.url()).pathname, "| hash sobrou:", JSON.stringify(new URL(p.url()).hash));
await p.screenshot({ path: join(PASTA, "convite-feliz-1-nova-senha.png") });
await p.fill("input[name=senha]", (process.env.NOVA ?? "Outra-Senha-12345"));
await p.fill("input[name=repetida]", (process.env.NOVA ?? "Outra-Senha-12345"));
await p.click("button[type=submit]");
await p.waitForURL((u) => !u.pathname.startsWith("/entrar"), { timeout: 20000 });
console.log("2) depois de salvar a senha:", new URL(p.url()).pathname, "(sem voltar ao /entrar)");
await p.waitForTimeout(2500);
await p.screenshot({ path: join(PASTA, "convite-feliz-2-app.png") });
console.log("erros de página:", erros.length ? erros : "nenhum");
await nav.close();
