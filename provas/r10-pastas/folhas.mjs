import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
const require = createRequire(join(process.env.APPDATA, "npm", "node_modules", "/"));
const { chromium } = require("playwright");
const PASTA = fileURLToPath(new URL("./", import.meta.url));
const IMG = join(PASTA, "..", "..", "public", process.argv[2]);
const nav = await chromium.launch({ args: ["--window-position=-3000,0"] });
for (const [w, h] of [[1440, 760], [390, 844]]) {
  const p = await nav.newPage({ viewport: { width: w, height: h } });
  await p.goto("http://localhost:3100/pastas", { waitUntil: "networkidle" });
  const beec = p.locator(".pastas-empresa", { hasText: "Beec" });
  const foto = async (n) => {
    await p.waitForTimeout(900);
    await p.evaluate(() => { document.getElementById("iw")?.remove(); const d = document.createElement("div"); d.id = "iw"; d.textContent = "innerWidth " + innerWidth; d.style.cssText = "position:fixed;left:8px;bottom:8px;z-index:2147483647;background:#fff;font:700 12px monospace;padding:4px 8px"; document.body.append(d); });
    await p.screenshot({ path: join(PASTA, `107-${n}-${w}.png`) });
  };
  const conta = async () => (await beec.locator(".gf-root", { hasText: "Posts" }).locator(".gf-meta").textContent());
  await beec.getByRole("button", { name: /^Abrir Posts/ }).scrollIntoViewIfNeeded();
  await beec.getByRole("button", { name: /^Abrir Posts/ }).click();
  console.log(w, "antes:", await conta());
  await foto("a-aberta");
  await beec.getByRole("button", { name: "+ Nova folha" }).click();
  await p.locator("input[name=titulo]:focus").waitFor();
  await p.keyboard.type("Folha teste");
  await p.locator("input[name=meta]").fill("PNG 1080x1350");
  await p.locator('input[type=file]').setInputFiles(IMG);
  await p.locator("input[name=link]").fill("https://drive.google.com/file/d/teste/view");
  await p.locator("textarea[name=notas]").fill("Notas da folha de teste");
  await foto("b-nova");
  await p.getByRole("button", { name: "Criar folha" }).click();
  await p.waitForTimeout(500);
  console.log(w, "depois de criar:", await conta());
  await foto("c-criada");
  const sheet = (n) => beec.locator(".gf-sheet", { hasText: n });
  await sheet("Folha teste").click();
  await foto("e-folha");
  await p.getByRole("button", { name: "Editar" }).click();
  await p.locator("input[name=titulo]:focus").waitFor();
  await p.keyboard.press("Control+A");
  await p.keyboard.type("Folha editada");
  await p.getByRole("button", { name: "Salvar" }).click();
  await p.waitForTimeout(400);
  await sheet("Folha editada").click();
  console.log(w, "título aberto:", await p.locator("dialog[open] h2").textContent());
  await foto("f-editada");
  await p.getByRole("button", { name: "Excluir" }).click();
  await foto("g-confirma");
  await p.getByRole("button", { name: "Excluir" }).click();
  await p.waitForTimeout(500);
  console.log(w, "depois de excluir:", await conta());
  await foto("h-excluida");
  // "Ver todas" (a You tem 6 peças em Posts): o + Nova folha aparece também aí
  const you = p.locator(".pastas-empresa", { hasText: "You" }).first();
  await you.getByRole("button", { name: /Ver todas/ }).first().scrollIntoViewIfNeeded();
  await you.getByRole("button", { name: /Ver todas/ }).first().click();
  await foto("i-ver-todas");
  await p.close();
}
await nav.close();
