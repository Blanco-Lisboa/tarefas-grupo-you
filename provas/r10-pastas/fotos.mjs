import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
const require = createRequire(join(process.env.APPDATA, "npm", "node_modules", "/"));
const { chromium } = require("playwright");
const PASTA = fileURLToPath(new URL("./", import.meta.url));
const nav = await chromium.launch({ args: ["--window-position=-3000,0"] });
for (const [w, h] of [[1440, 760], [390, 844]]) {
  const p = await nav.newPage({ viewport: { width: w, height: h } });
  await p.goto("http://localhost:3100/pastas", { waitUntil: "networkidle" });
  await p.evaluate(() => localStorage.removeItem("grade-conteudo:pastas:v1"));
  await p.reload({ waitUntil: "networkidle" });
  const beec = p.locator(".pastas-empresa", { hasText: "Beec" });
  const foto = async (n) => {
    await p.waitForTimeout(900);
    await p.evaluate(() => { document.getElementById("iw")?.remove(); const d = document.createElement("div"); d.id = "iw"; d.textContent = "innerWidth " + innerWidth; d.style.cssText = "position:fixed;left:8px;bottom:8px;z-index:2147483647;background:#fff;font:700 12px monospace;padding:4px 8px"; document.body.append(d); });
    await p.screenshot({ path: join(PASTA, `101-v2-${n}-${w}.png`) });
  };
  const nomes = () => beec.locator(".gf-title").allTextContents();
  await beec.locator(".pastas-nova").scrollIntoViewIfNeeded();
  await foto("a-botao");
  await beec.locator(".pastas-nova").click();
  await p.locator("input[name=nome]:focus").waitFor();
  await p.keyboard.type("Teste");
  await foto("b-nome");
  await p.getByRole("button", { name: "Criar pasta" }).click();
  await p.waitForTimeout(500);
  console.log(w, "depois de criar:", await nomes());
  await foto("c-criada");
  await beec.getByRole("button", { name: "Mais opções: Teste" }).click();
  await foto("d-menu");
  await p.getByRole("button", { name: "Renomear" }).click();
  await p.locator("input[name=nome]:focus").waitFor();
  await p.keyboard.press("Control+A");
  await p.keyboard.type("Teste renomeada");
  await p.getByRole("button", { name: "Salvar" }).click();
  await p.waitForTimeout(500);
  console.log(w, "depois de renomear:", await nomes());
  await foto("e-renomeada");
  await beec.getByRole("button", { name: "Mais opções: Posts" }).click();
  await p.getByRole("button", { name: "Excluir" }).click();
  await foto("f-nao-exclui");
  await p.getByRole("button", { name: "Entendi" }).click();
  await beec.getByRole("button", { name: "Mais opções: Teste renomeada" }).click();
  await p.getByRole("button", { name: "Excluir" }).click();
  await foto("g-confirma");
  await p.getByRole("button", { name: "Manter" }).click();
  console.log(w, "mantida:", await nomes());
  await p.close();
}
await nav.close();
