import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
const require = createRequire(join(process.env.APPDATA, "npm", "node_modules", "/"));
const { chromium } = require("playwright");
const PASTA = fileURLToPath(new URL("./", import.meta.url));
const nav = await chromium.launch({ args: ["--window-position=-3000,0"] });
const p = await nav.newPage({ viewport: { width: 1440, height: 760 } });
p.on("pageerror", (e) => console.log("pageerror", String(e)));
const abrir = async () => {
  await p.goto("http://127.0.0.1:3131/pastas", { waitUntil: "load" }); await p.waitForTimeout(1500);
  await p.locator("button:has-text('Ideias de conteúdo'), [aria-label*='Ideias']").first().click(); await p.waitForTimeout(1200);
};
const foto = (n) => p.screenshot({ path: `${PASTA}${n}.png` });
// cola uma imagem de verdade (PNG gerado no navegador) no campo em foco, como o Ctrl+V do Maestri
const colar = (cor, texto) => p.evaluate(async ([cor, texto]) => {
  const c = document.createElement("canvas"); c.width = 640; c.height = 420;
  const x = c.getContext("2d"); x.fillStyle = cor; x.fillRect(0, 0, 640, 420); x.fillStyle = "#fff"; x.font = "bold 56px sans-serif"; x.fillText(texto, 40, 220);
  const blob = await new Promise((ok) => c.toBlob(ok, "image/png"));
  const dt = new DataTransfer(); dt.items.add(new File([blob], "print.png", { type: "image/png" }));
  document.activeElement.dispatchEvent(new ClipboardEvent("paste", { clipboardData: dt, bubbles: true, cancelable: true }));
}, [cor, texto]);
await p.goto("http://127.0.0.1:3231/entrar", { waitUntil: "load" }); await p.waitForTimeout(800);
await abrir();
const folha = p.locator("article.mural-folha").first();
await folha.locator("textarea.mural-detalhe").click(); await p.waitForTimeout(300);
console.log("prints antes:", await folha.locator(".mural-print").count());
await foto("300-1-antes-dica-1440");
await colar("#2f6fed", "Print 1"); await p.waitForTimeout(1500);
await colar("#e0603a", "Print 2"); await p.waitForTimeout(1500);
await colar("#2a9d6f", "Print 3"); await p.waitForTimeout(1500);
console.log("prints depois de colar 3:", await folha.locator(".mural-print").count());
await foto("300-2-colou-3-prints-1440");
await p.reload({ waitUntil: "load" }); await p.waitForTimeout(800); await abrir();
const f2 = p.locator("article.mural-folha").first();
console.log("depois de recarregar:", await f2.locator(".mural-print").count(), "imagens carregadas:", await f2.locator(".mural-print img").evaluateAll((l) => l.filter((i) => i.naturalWidth > 0).length));
await foto("300-3-recarregou-1440");
await f2.locator(".mural-print-ver").nth(1).click(); await p.waitForTimeout(500);
await foto("300-4-ampliado-1440");
await p.keyboard.press("Escape"); await p.waitForTimeout(300);
console.log("lupa aberta depois do Esc:", await p.locator("dialog[open]").count());
await foto("300-4b-depois-do-esc-1440"); console.log("mural aberto:", await p.locator(".mural-quadro").count(), "prints:", await f2.locator(".mural-print").count());
await f2.locator(".mural-print").nth(1).hover();
await f2.locator(".mural-print-tirar").nth(1).click(); await p.waitForTimeout(300);
await foto("300-5-apagar-confirmar-1440");
await f2.locator(".mural-print-tirar").nth(1).click(); await p.waitForTimeout(1200);
console.log("depois de apagar 1:", await f2.locator(".mural-print").count());
await p.reload({ waitUntil: "load" }); await p.waitForTimeout(800); await abrir();
console.log("recarregou de novo:", await p.locator("article.mural-folha").first().locator(".mural-print").count());
await foto("300-6-apagou-recarregou-1440");
await nav.close();
